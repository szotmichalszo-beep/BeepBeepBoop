def add(a, b):
    return a + b

def subtract(a, b):
    return a - b

def multiply(a, b):
    return a * b

def divide(a, b):
    return a / b

print("Wynik dodawania:", add(5, 3))
print("Wynik odejmowania:", subtract(10, 4))
print("Wynik mnożenia:", multiply(8, 4))
print("Wynik dzielenia:", divide(234, 6))